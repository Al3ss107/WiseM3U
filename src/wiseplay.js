/* Tolerant JSON: many WisePlay files have a BOM, trailing commas,      */
/* control characters or HTML text before/after the payload.            */
/* ------------------------------------------------------------------ */

function stripControlChars(s) {
  // keeps \t \n \r, removes other control characters invalid in JSON
  return s.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');
}

function looksLikeJson(s) {
  const t = s.trim();
  return t.startsWith('{') || t.startsWith('[') || /"stations"\s*:|"groups"\s*:/.test(t);
}

/**
 * Removes the "spurious commas" typical of hand-written WisePlay gists:
 *   - virgola finale:   {"a":1,}  [1,2,]
 *   - empty element:    [.., , ..]   (appears in some "chained" lists)
 *   - virgola orfana:   [,..]  {,..}
 * The simple regex (,(\s*[}\]])) is not enough and would corrupt STRINGS
 * containing similar sequences: here we scan character by character,
 * respecting "..." delimiters and escapes.
 */
function removeStrayCommas(json) {
  const n = json.length;
  let out = '';
  let inStr = false;
  let esc = false;
  let prev = ''; // last NON-space character emitted
  for (let i = 0; i < n; i++) {
    const c = json[i];
    if (inStr) {
      out += c;
      if (esc) esc = false;
      else if (c === '\\') esc = true;
      else if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') { inStr = true; out += c; prev = c; continue; }
    if (c === ',') {
      // if the next significant character closes the structure or is another
      // comma, or the previous one opened the structure -> spurious comma: skip
      let j = i + 1;
      while (j < n && /\s/.test(json[j])) j++;
      const next = j < n ? json[j] : '';
      if (next === ',' || next === ']' || next === '}' || prev === '[' || prev === '{' || prev === ',') continue;
    }
    out += c;
    if (!/\s/.test(c)) prev = c;
  }
  return out;
}

function parseLenientJson(raw) {
  let s = String(raw || '').replace(/^\uFEFF/, '');
  s = stripControlChars(s);

  const attempts = [];
  attempts.push(s);

  // extract the JSON portion if there is noise around it (e.g. HTML)
  const firstBrace = s.indexOf('{');
  const firstBracket = s.indexOf('[');
  let start = -1;
  if (firstBrace >= 0 && firstBracket >= 0) start = Math.min(firstBrace, firstBracket);
  else start = Math.max(firstBrace, firstBracket);
  if (start > 0) {
    const body = s.slice(start);
    const close = body[0] === '{' ? body.lastIndexOf('}') : body.lastIndexOf(']');
    if (close > 0) attempts.push(body.slice(0, close + 1));
  }

  for (const candidate of attempts) {
    try {
      return JSON.parse(candidate);
    } catch (_) {
      /* next */
    }
  }

  // last resort: cleaned version (trailing/spurious commas, empty elements)
  for (const candidate of attempts) {
    try {
      return JSON.parse(removeStrayCommas(candidate));
    } catch (_) {
      /* next */
    }
  }

  return null;
}

