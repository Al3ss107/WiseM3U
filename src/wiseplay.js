/** Format label from the first bytes: tells the user what it really is
 *  before the URL. '' = unrecognized. */
function magicLabel(b) {
  if (!b || b.length < 4) return '';
  const s4 = b.subarray(0, 4).toString('latin1');
  const ascii4 = (from, to) => (b.length >= to ? b.subarray(from, to).toString('latin1') : '');
  if (b[0] === 0x1f && b[1] === 0x8b) return 'GZIP ARCHIVE';
  if (b[0] === 0x50 && b[1] === 0x4b) return 'ZIP ARCHIVE';
  if (s4 === 'Rar!') return 'RAR ARCHIVE';
  if (s4 === '7z\u00bc\u00af') return '7Z ARCHIVE';
  if (ascii4(4, 8) === 'ftyp') return 'VIDEO MP4/MOV';
  if (b[0] === 0x1a && b[1] === 0x45 && b[2] === 0xdf && b[3] === 0xa3) return 'VIDEO MKV/WEBM';
  if (s4 === 'FLV\x01') return 'VIDEO FLV';
  // MPEG-TS: 0x47 sync byte every 188 bytes (a channel "stream")
  if (b.length >= 377 && b[0] === 0x47 && b[188] === 0x47 && b[376] === 0x47) return 'STREAM VIDEO MPEG-TS';
  if (s4 === '\x00\x00\x01\xba' || s4 === '\x00\x00\x01\xb3') return 'VIDEO MPEG-PS';
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e) return 'IMMAGINE PNG';
  if (b[0] === 0xff && b[1] === 0xd8) return 'IMMAGINE JPEG';
  if (s4 === 'GIF8') return 'IMMAGINE GIF';
  if (s4 === 'RIFF' && ascii4(8, 12) === 'AVI ') return 'VIDEO AVI';
  return '';
}

/** Readable text (m3u/json/html)? Tolerates UTF-16 with its NULs. */
function looksTextual(b) {
  const head = b.subarray(0, 2048);
  if (!head.length) return true;
  let nul = 0;
  let ctrl = 0;
  for (const x of head) {
    if (x === 0) nul++;
    else if (x < 9 || (x > 13 && x < 32)) ctrl++;
  }
  if (nul > head.length * 0.02) return isUtf16(head);
  return ctrl <= head.length * 0.02;
}

/** UTF-16 without BOM: half the bytes are zero, all of the same parity. */
function isUtf16(head) {
  const n = Math.min(head.length, 512);
  if (n < 16) return false;
  let zeroEven = 0;
  let zeroOdd = 0;
  let printable = 0;
  let nonZero = 0;
  for (let i = 0; i < n; i++) {
    const x = head[i];
    if (x === 0) {
      if (i % 2 === 0) zeroEven++; else zeroOdd++;
    } else {
      nonZero++;
      if ((x >= 9 && x <= 13) || (x >= 32 && x < 127)) printable++;
    }
  }
  const half = n / 2;
  // UTF-16 text has ~half non-null bytes and almost all printable: a
  // binary with few useful bytes and many zeros (zip, video) is NOT UTF-16
  if (nonZero < n * 0.2) return false;
  if (printable < nonZero * 0.85) return false;
  return zeroEven > half * 0.6 || zeroOdd > half * 0.6;
}

/** Compact preview to tell us what is behind the URL. */
function headPreview(b) {
  if (!b || !b.length) return '';
  const hex = b.subarray(0, 16).toString('hex').replace(/(..)/g, '$1 ').trim();
  const pretty = b.subarray(0, 60).toString('latin1').replace(/[^\x20-\x7e]/g, '.');
  return `primi byte: "${pretty}" [${hex}]`;
}

/** Quick M3U entry count: to distinguish a "huge playlist" from a
 *  "video file" when the limit is exceeded. */
function countM3uEntries(text) {
  const m = text.match(/#EXTINF/g);
  return m ? m.length : 0;
}

/**
 * Definitive error: retrying is useless. The link points to something else
 * (video, archive, binary) or the playlist exceeds the memory limit.
 *
 * Previously EVERYTHING was downloaded (e.g. 609 MB) and only at the end
 * was it clear it was too large: RAM full, 60s wasted and "Refresh" repeating
 * the same 609 MB download.
 * The limit applies while streaming, and we no longer reject based
 * only on the Content-Length header (PHP panels often get it wrong):
 * if the body ends before the limit, the list is imported.
 */
function tooLargeError(size, contentType, head, opts = {}) {
  const mb = (size / 1048576).toFixed(1);
  const ct = String(contentType || '').split(';')[0].trim().toLowerCase();
  const headBuf = head || Buffer.alloc(0);
  const magic = magicLabel(headBuf);
  const textual = looksTextual(headBuf);
  const declared =
    opts.declared && opts.declared > size * 1.2
      ? ` (the server declared ${(opts.declared / 1048576).toFixed(1)} MB)`
      : '';

  let why;
  if (magic && /ARCHIVE/.test(magic)) {
    why =
      `the URL returned ${magic}, not a playlist` +
      (magic === 'ZIP ARCHIVE'
        ? ': extract the .m3u file from the zip and upload it, or use the direct get.php link'
        : '');
  } else if (magic) {
    why = `the URL returned ${magic}, not a playlist`;
  } else if (/^(video|audio)\//.test(ct) && !/mpegurl/.test(ct)) {
    why = `the URL returned a ${ct.includes('audio') ? 'AUDIO FILE' : 'VIDEO FILE'} (content-type ${ct}), not a playlist`;
  } else if (textual) {
    const limMb = (opts.limit || MAX_BYTES) / 1048576;
    const limTxt = `${limMb >= 10 ? Math.round(limMb) : limMb.toFixed(1).replace(/\.0$/, '')} MB`;
    const entries = countM3uEntries(headBuf.toString('latin1'));
    why = entries
      ? `it is a text PLAYLIST exceeding the ${limTxt} limit ` +
        `(${entries} entries in the first ${(headBuf.length / 1024).toFixed(0)} KB): the catalog is too large`
      : `it is TEXT exceeding the ${limTxt} limit and not an m3u ` +
        `(m3u lists are streamed, with no MB limit)`;
    // note: m3u files do not go through here (streaming import in fetchRootAuto)
  } else {
    why =
      `the URL returned a BINARY file (content-type ${ct || 'missing'}; ${headPreview(headBuf)}), not a playlist`;
  }

  const intro = size > 0 ? `Response too large (${mb} MB)` : 'Unusable response';
  const err = new FetchError(
    `${intro}${declared}: ${why}. ` +
      'Check the link: an Xtream panel requires .../get.php?username=…&password=…&type=m3u_plus&output=ts ' +
      '(not a single-channel stream or an .mp4/.mkv file).',
    0
  );
  err.fatal = true; // no useless retries (see fetchRoot)
  return err;
}

/** Decompresses gzip and normalizes text encodings (BOM / UTF-16). */
function decodeBody(buf) {
  let b = buf;
  // raw gzip served as application/octet-stream (no Content-Encoding):
  // undici does not decompress it, so we do it with an output cap
  for (let i = 0; i < 2 && b.length > 2 && b[0] === 0x1f && b[1] === 0x8b; i++) {
    try {
      b = zlib.gunzipSync(b, { maxOutputLength: MAX_BYTES });
    } catch (e) {
      const err = new FetchError(
        `The response is gzip-compressed but expands beyond the ${Math.round(MAX_BYTES / 1048576)} MB limit ` +
          `(or is corrupted): it cannot be used as a playlist.`,
        0
      );
      err.fatal = true;
      throw err;
    }
  }
  if (b.length >= 3 && b[0] === 0xef && b[1] === 0xbb && b[2] === 0xbf) b = b.subarray(3);
  if (b.length >= 2 && b[0] === 0xff && b[1] === 0xfe) return b.subarray(2).toString('utf16le');
  if (b.length >= 2 && b[0] === 0xfe && b[1] === 0xff) {
    // UTF-16BE -> swap pairs and reuse the LE decoder
    const c = Buffer.from(b.subarray(2));
    for (let i = 0; i + 1 < c.length; i += 2) {
      const t = c[i];
      c[i] = c[i + 1];
      c[i + 1] = t;
    }
    return c.toString('utf16le');
  }
  if (isUtf16(b)) return b.toString('utf16le');
  return b.toString('utf8');
}

const SNIFF_BYTES = 4096; // enough bytes to understand what we are downloading

/** Accumulates chunks applying the limit (used by the "text" path).
 *  `limit` is parameterized only for tests: in production it is MAX_BYTES. */
async function collectCapped(chunks, ct, declared, limit = MAX_BYTES) {
  const out = [];
  let size = 0;
  let head = null;
  for await (const c of chunks) {
    if (!head) head = c.slice(0, SNIFF_BYTES);
    size += c.length;
    if (size > limit) {
      throw tooLargeError(size, ct, head, { declared: declared > size ? declared : 0, limit });
    }
    // inflated header + content already recognizable as non-text:
    // no point downloading 60 MB of a video. Only the first KB are inspected.
    if (declared > limit && size >= SNIFF_BYTES && !looksTextual(head) && magicLabel(head) !== 'GZIP ARCHIVE') {
      throw tooLargeError(declared, ct, head, { declared, limit });
    }
    out.push(c);
  }
  return Buffer.concat(out);
}

/** Reads the body applying the limit DURING download (streaming). */
async function readCapped(res, url) {
  const ct = res.headers.get('content-type') || '';
  const declared = Number(res.headers.get('content-length') || 0);
  if (!res.body) throw new FetchError(`Empty response from ${url}`, res.status);

  // an explicit movie/audio is never a playlist (mpegurl is the old
  // MIME type for .m3u: we accept that one)
  if (/^(video|audio)\//.test(ct) && !/mpegurl/.test(ct)) {
    try { await res.body.cancel(); } catch (_) { /* ignora */ }
    throw tooLargeError(declared, ct, null);
  }
  const reader = res.body.getReader();
  return collectCapped(streamChunks(reader, null), ct, declared);
}

async function fetchText(url, opts = {}) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), opts.timeout || FETCH_TIMEOUT_MS);
  try {
    const res = await fetch(url, {
      redirect: 'follow',
      signal: ctrl.signal,
      headers: {
        'User-Agent': getUserAgent(opts && opts.userAgent),
        Accept: 'application/json, text/plain, application/x-mpegurl, */*',
      },
    });
    if (!res.ok) throw new FetchError(`HTTP ${res.status} for ${url}`, res.status);
    const buf = await readCapped(res, url);
    return decodeBody(buf);
  } catch (err) {
    if (err && err.fatal) throw err; // already diagnosed, do not wrap
    throw fetchFailure(err, url);
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Fallback fetch with native http/https modules (redirects handled manually).
 * Used ONLY in the specific cases where undici fails:
 *  - opts.insecure: untrusted TLS certificate -> skip verification
 *    (self-signed/expired, very common with self-hosted Xtream panels);
 *  - opts.ip: local/container DNS cannot resolve the domain -> connect
 *    directly by IP (Host and SNI stay the domain, so vhosts answer).
 */
function nodeFetchText(url, opts = {}, redirectsLeft = 5) {
  return new Promise((resolve, reject) => {
    let u;
    try { u = new URL(url); } catch (_) { return reject(new FetchError('invalid URL', 0)); }
    const isHttps = u.protocol === 'https:';
    const lib = isHttps ? https : http;
    const connectHost = opts.ip || u.hostname;
    const headers = {
      'User-Agent': getUserAgent(opts && opts.userAgent),
      Accept: 'application/json, text/plain, application/x-mpegurl, */*',
      'Accept-Encoding': 'identity', // no compression: it is not decompressed here
    };
    if (opts.ip) headers.host = u.host; // connected by IP: the vhost must still see the domain
    const requestOpts = {
      host: connectHost,
      port: u.port || (isHttps ? 443 : 80),
      path: u.pathname + (u.search || ''),
      headers,
      timeout: opts.timeout || FETCH_TIMEOUT_MS,
    };
    if (isHttps) {
      if (opts.insecure) requestOpts.rejectUnauthorized = false;
      // SNI: always the domain (never to an IP, RFC 6066)
      if (!net.isIP(u.hostname)) requestOpts.servername = u.hostname;
    }
    const req = lib.get(requestOpts, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location && redirectsLeft > 0) {
        res.resume();
        const next = new URL(res.headers.location, url).toString();
        return resolve(nodeFetchText(next, opts, redirectsLeft - 1));
      }
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new FetchError(`HTTP ${res.statusCode} for ${url}`, res.statusCode));
      }
      const chunks = [];
      let size = 0;
      let head = null;
      let aborted = false;
      const ct = res.headers['content-type'] || '';
      const len = Number(res.headers['content-length'] || 0);
      res.on('data', (c) => {
        if (aborted) return;
        if (!head) head = c.slice(0, 512);
        size += c.length;
        if (size > MAX_BYTES) {
          // streaming: closes the socket immediately instead of reading 600 MB
          aborted = true;
          res.destroy();
          return reject(tooLargeError(size, ct, head, { declared: len > size ? len : 0 }));
        }
        if (len > MAX_BYTES && size >= SNIFF_BYTES && !looksTextual(head) && magicLabel(head) !== 'GZIP ARCHIVE') {
          aborted = true;
          res.destroy();
          return reject(tooLargeError(len, ct, head, { declared: len }));
        }
        chunks.push(c);
      });
      res.on('end', () => {
        if (aborted) return;
        try { resolve(decodeBody(Buffer.concat(chunks))); } catch (e) { reject(e); }
      });
      res.on('error', (e) => reject(fetchFailure(e, url)));
    });
    req.on('timeout', () => req.destroy(new FetchError(`timeout after ${opts.timeout || FETCH_TIMEOUT_MS} ms`, 0)));
    req.on('error', (e) => reject(e instanceof FetchError ? e : fetchFailure(e, url)));
  });
}

/** Resolves a hostname using public DNS (1.1.1.1 / 8.8.8.8). */
function resolveViaPublicDns(hostname) {
  const r = new Resolver();
  r.setServers(['1.1.1.1', '8.8.8.8']);
  return Promise.race([
    r.resolve4(hostname).then((a) => a[0]),
    new Promise((resolve, rej) => {
      const t = setTimeout(() => rej(new Error('public DNS timeout')), 4000);
      if (t.unref) t.unref();
    }),
  ]);
}

function isM3uText(text) {
  return /^\uFEFF?\s*#EXTM3U/im.test(text) || /#EXTINF\s*:/i.test(text);
}

/** HTML page (GitHub blob/tree, file preview, login page...) instead of a file. */
function looksLikeHtml(text) {
  const head = String(text || '').replace(/^\uFEFF/, '').trimStart().slice(0, 4096);
  return /^<!doctype\s+html\b/i.test(head) || /<html[\s>]/i.test(head) || /<head[\s>]/i.test(head) || /<body[\s>]/i.test(head);
}

function guessKind(url, text) {
  if (isM3uText(text)) return 'm3u';
  // keep the tolerant JSON path first: some public lists wrap the object in
  // an HTML shell; only pure HTML is rejected
  if (looksLikeJson(text)) return 'json';
  if (looksLikeHtml(text)) return 'html';
  if (/\.m3u8?(\?|$)/i.test(url)) return 'm3u';
  if (/\.json(\?|$)/i.test(url)) return 'json';
  return 'unknown';
}

/**
 * Converts an M3U playlist into an equivalent WisePlay tree: one group per
 * group-title (channels without a group go to "General"), so the rest of the
 * pipeline (branches, genres, selection, output) stays identical.
 */
function m3uToWisePlay(text, rootUrl) {
  const { header, entries } = parseM3U(text, 'Generale');
  const groups = new Map();
  for (const e of entries) {
    const g = (e.group || 'Generale').trim() || 'Generale';
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push({ name: e.name, image: e.logo || '', url: e.url });
  }
  const name = (header.name || header.title || '').toString().trim() || m3uDefaultName(rootUrl);
  return {
    kind: 'm3u',
    name,
    author: 'M3U',
    info:
      `M3U playlist (${entries.length} channels)` +
      (header['x-tvg-url'] || header['url-tvg'] ? ' · EPG incluso' : ''),
    url: rootUrl,
    // m3u_plus: the EPG declared by the source (x-tvg-url/url-tvg) propagates
    // to the final playlist generated by the addon
    epgUrls: epgUrlsFromHeader(header),
    groups: [...groups.entries()].map(([g, stations]) => ({ name: g, stations })),
  };
}

